// Writes src/data/licences.generated.ts: name, version and licence of every package the app ships directly
// (package.json "dependencies", plus the Inter font package that is embedded in the PDFs). Run after changing a
// dependency: node scripts/licences.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
const names = [...Object.keys(pkg.dependencies), '@fontsource/inter'].sort((a, b) => a.localeCompare(b));
const rows = names.map((name) => {
  const p = JSON.parse(readFileSync(`node_modules/${name}/package.json`, 'utf8'));
  const license = typeof p.license === 'string' ? p.license : (p.license?.type ?? (p.licenses ?? []).map((l) => l.type).join(' OR ')) || 'see package';
  return { name, version: p.version, license };
});
const body = rows.map((r) => `  { name: '${r.name}', version: '${r.version}', license: '${r.license.replace(/'/g, "\\'")}' },`).join('\n');
writeFileSync(
  'src/data/licences.generated.ts',
  `// Generated by scripts/licences.mjs from package.json and node_modules — do not edit by hand.\nexport const LICENCES: readonly { name: string; version: string; license: string }[] = [\n${body}\n];\n`
);
console.log(`${rows.length} packages: ${[...new Set(rows.map((r) => r.license))].join(', ')}`);
