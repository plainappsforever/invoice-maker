// Build-time: embeds Inter (SIL OFL 1.1, @fontsource/inter 5.3.0) as base64 woff2 @font-face CSS in
// src/render/fonts.generated.ts, so the PDF templates carry their own font and look the same on iOS and
// Android (D23). Latin + latin-ext, weights 400 and 600. Run: node scripts/embed-fonts.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const files = join(root, 'node_modules', '@fontsource', 'inter', 'files');
const version = JSON.parse(readFileSync(join(root, 'node_modules', '@fontsource', 'inter', 'package.json'), 'utf8')).version;

const UNICODE = JSON.parse(readFileSync(join(root, 'node_modules', '@fontsource', 'inter', 'unicode.json'), 'utf8'));
const RANGES = { latin: UNICODE.latin, 'latin-ext': UNICODE['latin-ext'] };

const faces = [];
for (const weight of [400, 600]) {
  for (const subset of ['latin-ext', 'latin']) {
    const b64 = readFileSync(join(files, `inter-${subset}-${weight}-normal.woff2`)).toString('base64');
    faces.push(
      `@font-face{font-family:'Inter';font-style:normal;font-weight:${weight};font-display:block;` +
        `src:url(data:font/woff2;base64,${b64}) format('woff2');unicode-range:${RANGES[subset]};}`
    );
  }
}

const out = `// GENERATED by scripts/embed-fonts.mjs from @fontsource/inter ${version} (SIL OFL 1.1, see assets/fonts/OFL.txt).
// Do not edit by hand; run \`node scripts/embed-fonts.mjs\`.
export const FONT_FACE_CSS = ${JSON.stringify(faces.join('\n'))};
export const FONT_FAMILY = "'Inter', 'Helvetica Neue', Helvetica, Arial, sans-serif";
`;
writeFileSync(join(root, 'src', 'render', 'fonts.generated.ts'), out);
console.log(`wrote src/render/fonts.generated.ts (${out.length} bytes, Inter ${version})`);
